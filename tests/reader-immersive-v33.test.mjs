import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const base=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const css=fs.readFileSync(path.join(base,'reader-immersive-v33.css'),'utf8');
const js=fs.readFileSync(path.join(base,'reader-immersive-v33.js'),'utf8');
const app=fs.readFileSync(path.join(base,'app.js'),'utf8');
const sw=fs.readFileSync(path.join(base,'sw.js'),'utf8');
assert(html.includes('reader-immersive-v33.css?v=33')&&html.includes('reader-immersive-v33.js?v=33'),'Reader files not included');
assert(html.includes('reader-scene-hero')&&html.includes('reader-scene-layer'),'Missing image hero');
assert(html.includes('id="voiceCycleBtn"')&&html.includes('id="speedCycleBtn"'),'Missing direct player controls');
assert(html.includes('class="reader-native-select" tabindex="-1" aria-hidden="true"'),'Original select must stay internal only');
assert(css.includes('.side-nav,')&&css.includes('.mascot-area,')&&css.includes('display:none!important'),'Sidebars should be hidden');
assert(css.includes('reader-ken-burns-v33')&&css.includes('transition:opacity'),'Hero needs pan/zoom + crossfade');
assert(css.includes('prefers-reduced-motion:reduce'),'Reduced-motion support required');
assert(css.includes('max-width:1180px!important')&&css.includes('max-width:72ch!important'),'Reader must be centered and readable');
assert(css.includes('12s linear both paused')&&css.includes('opacity 1750ms'),'Motion and crossfade must be visible');
assert(js.includes('ROTATION_MS=7500')&&js.includes('getSceneFiles'),'Paused reading must still show animated illustrations');
assert(app.includes('getSceneFiles:'),'App must expose story images to the gallery');
assert(js.includes("document.addEventListener('barti:scene-change'"),'Missing scene-update subscription');
assert(js.includes("voice.dispatchEvent(new Event('change'"),'Voice control must trigger original engine');
assert(js.includes("speed.dispatchEvent(new Event('change'"),'Speed control must trigger original engine');
assert(app.includes("document.dispatchEvent(new CustomEvent('barti:scene-change'"),'Reading engine not emitting scene');
assert(sw.includes('reader-immersive-v33.css?v=33')&&sw.includes('reader-immersive-v33.js?v=33'),'Missing offline asset entries');
console.log('PASS: fullscreen reader, animated sentence heroes, direct working buttons, inline dictionary, PWA integration.');
